#!/usr/bin/env python3
"""Preflight the design sheets, then generate src/Zombheim/Generated/Sheets.g.cs.

Every row x column cell must be filled; every cross-sheet reference must resolve;
every hook handler must exist in the plugin source. The build refuses to run otherwise.
Usage: python3 tools/sheets.py [--check]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHEETS = ROOT / "sheets"
SRC = ROOT / "src" / "Zombheim"
OUT = SRC / "Generated" / "Sheets.g.cs"

# (sheet, column) -> sheet whose ids it references
REFS = {
    ("enemies", "drops"): "items",
    ("waves", "enemy"): "enemies",
    ("tuning", "usedBy"): "systems",
    ("systems", "hooks"): "hooks",
    ("hooks", "system"): "systems",
}


def load():
    sheets = {}
    for p in sorted(SHEETS.glob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        sheets[d["sheet"]] = d
    return sheets


def preflight(sheets):
    problems = []
    ids = {name: {r["id"] for r in s["rows"]} for name, s in sheets.items()}
    for name, s in sheets.items():
        cols = s["columns"]
        seen = set()
        for i, row in enumerate(s["rows"]):
            rid = row.get("id", f"#{i}")
            if rid in seen:
                problems.append(f"{name}.{rid}: duplicate id")
            seen.add(rid)
            for c in cols:
                v = row.get(c)
                if v is None or (isinstance(v, str) and v.strip() == ""):
                    problems.append(f"{name}.{rid}.{c}: unfilled")
            for k in row:
                if k not in cols:
                    problems.append(f"{name}.{rid}.{k}: not a column of the sheet")
            for c in cols:
                ref = REFS.get((name, c))
                if ref:
                    vals = row.get(c) or []
                    for v in vals if isinstance(vals, list) else [vals]:
                        if v not in ids.get(ref, set()):
                            problems.append(f"{name}.{rid}.{c}: '{v}' is not an id in {ref}")
            if name == "systems":
                for d in row.get("data", []):
                    if d not in sheets:
                        problems.append(f"systems.{rid}.data: no sheet '{d}'")
    # every hook handler must exist in the plugin source
    src = "\n".join(p.read_text(encoding="utf-8") for p in SRC.rglob("*.cs") if "Generated" not in p.parts)
    for row in sheets["hooks"]["rows"]:
        cls, meth = row["handler"].split(".")
        if not re.search(r"class\s+" + cls + r"\b", src) or not re.search(r"static\s+void\s+" + meth + r"\s*\(", src):
            problems.append(f"hooks.{row['id']}.handler: {row['handler']} not found in src")
        if row["kind"] not in ("prefix", "postfix"):
            problems.append(f"hooks.{row['id']}.kind: must be prefix or postfix")
    # every hook belongs to a system that lists it
    listed = {h for r in sheets["systems"]["rows"] for h in r["hooks"]}
    for row in sheets["hooks"]["rows"]:
        if row["id"] not in listed:
            problems.append(f"hooks.{row['id']}: no system lists it")
    # every tuning value is read by the code
    for row in sheets["tuning"]["rows"]:
        if f'Tuning.{row["id"][0].upper()}{row["id"][1:]}' not in src:
            problems.append(f"tuning.{row['id']}: never read by src")
    total = sum(r["chance"] for r in sheets["wounds"]["rows"])
    if abs(total - 1.0) > 1e-6:
        problems.append(f"wounds.chance: column sums to {total}, must be 1")
    stages = [r["afterSeconds"] for r in sheets["infection"]["rows"]]
    if stages != sorted(stages):
        problems.append("infection.afterSeconds: stages must be in order")
    kinds = {"weapon", "food", "medical"}
    for r in sheets["items"]["rows"]:
        if r["kind"] not in kinds:
            problems.append(f"items.{r['id']}.kind: must be one of {sorted(kinds)}")
    return problems


def pascal(s):
    return s[0].upper() + s[1:]


def cs_type(values):
    if all(isinstance(v, bool) for v in values):
        return "bool"
    if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in values):
        return "float"
    if all(isinstance(v, list) for v in values):
        return "string[]"
    return "string"


def cs_value(v, t):
    if t == "bool":
        return "true" if v else "false"
    if t == "float":
        return f"{float(v)!r}f"
    if t == "string[]":
        return "new string[] { " + ", ".join(json.dumps(x) for x in v) + " }"
    return json.dumps(v)


def generate(sheets):
    out = ["// <auto-generated> from sheets/*.json by tools/sheets.py. Edit the sheets, not this file. </auto-generated>",
           "namespace Zombheim", "{"]
    for name, s in sheets.items():
        if name == "tuning":
            continue
        cls = pascal(name).rstrip("s") + "Row"
        types = {c: cs_type([r[c] for r in s["rows"]]) for c in s["columns"]}
        out.append(f"    public sealed class {cls}")
        out.append("    {")
        for c in s["columns"]:
            out.append(f"        public {types[c]} {pascal(c)};")
        out.append("    }")
        out.append("")
    out.append("    public static class Sheets")
    out.append("    {")
    for name, s in sheets.items():
        if name == "tuning":
            continue
        cls = pascal(name).rstrip("s") + "Row"
        types = {c: cs_type([r[c] for r in s["rows"]]) for c in s["columns"]}
        out.append(f"        public static readonly {cls}[] {pascal(name)} =")
        out.append("        {")
        for r in s["rows"]:
            fields = ", ".join(f"{pascal(c)} = {cs_value(r[c], types[c])}" for c in s["columns"])
            out.append(f"            new {cls} {{ {fields} }},")
        out.append("        };")
    out.append("    }")
    out.append("")
    out.append("    public static class Tuning")
    out.append("    {")
    for r in sheets["tuning"]["rows"]:
        out.append(f"        /// <summary>{r['unit']} (used by {r['usedBy']})</summary>")
        out.append(f"        public const float {pascal(r['id'])} = {float(r['value'])!r}f;")
    out.append("    }")
    out.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")


def main():
    sheets = load()
    problems = preflight(sheets)
    cells = sum(len(s["rows"]) * len(s["columns"]) for s in sheets.values())
    if problems:
        print(f"PREFLIGHT FAILED ({len(problems)} problems over {cells} cells):")
        for p in problems:
            print("  - " + p)
        sys.exit(1)
    print(f"preflight clean: {len(sheets)} sheets, {cells} cells checked, all references resolve")
    if "--check" not in sys.argv:
        generate(sheets)
        print(f"generated {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
